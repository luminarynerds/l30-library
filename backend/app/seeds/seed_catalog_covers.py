async def seed_catalog_covers(session: AsyncSession):
    result = await session.execute(select(CatalogItem))
    items = result.scalars().all()

    updated = 0
    for item in items:
        url = COVERS.get(item.id)
        if url and item.cover_url != url:
            item.cover_url = url
            updated += 1

    if updated:
        await session.commit()
    print(f"  Catalog covers: {updated} updated, {len(items) - updated} unchanged")
