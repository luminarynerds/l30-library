@router.post(
    "/{club_id}/members/import",
    response_model=MemberImportResponse,
)
async def import_book_club_members(
    club_id: int,
    file: UploadFile = File(...),
    default_role: str = Form("member"),
    dry_run: bool = Form(False),
    staff_user: User = Depends(require_staff),
    db: AsyncSession = Depends(get_db),
    _flag: None = Depends(require_book_clubs_enabled),
) -> MemberImportResponse:
    """Bulk-import book club members from a CSV file.

    Multipart fields: ``file`` (UploadFile), ``default_role`` ("member" |
    "facilitator" | "admin"), ``dry_run`` (bool).

    Returns 200 with per-row outcomes even on partial failure; reserves
    4xx for request-level errors (missing club, oversized file, bad
    headers, bad ``default_role``).
    """
    valid_roles = {"member", "facilitator", "admin"}
    if default_role not in valid_roles:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="default_role must be one of: admin, facilitator, member",
        )

    # Verify club exists.
    result = await db.execute(select(BookClub).where(BookClub.id == club_id))
    if result.scalar_one_or_none() is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Book club not found",
        )

    # Read + BOM-tolerant decode.
    raw = await file.read()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="CSV must be UTF-8 encoded.",
        ) from None

    reader = csv.DictReader(io.StringIO(text))
    # Header validation: must include email OR patron_id (role optional).
    fieldnames = [(f or "").strip().lower() for f in (reader.fieldnames or [])]
    if not fieldnames or ("email" not in fieldnames and "patron_id" not in fieldnames):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="CSV must include an email or patron_id column.",
        )

    # Normalise dict keys to lowercase for downstream lookups.
    rows: list[dict] = []
    for raw_row in reader:
        norm = {(k or "").strip().lower(): v for k, v in raw_row.items() if k is not None}
        rows.append(norm)

    if len(rows) == 0:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="CSV has no data rows.",
        )

    from app.services.book_club_service import MAX_IMPORT_ROWS
    if len(rows) > MAX_IMPORT_ROWS:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"CSV exceeds {MAX_IMPORT_ROWS} row limit (got {len(rows)}).",
        )

    payload = await book_club_service.import_members(
        club_id=club_id,
        rows=rows,
        default_role=default_role,
        dry_run=dry_run,
        imported_by_id=staff_user.id,
        db=db,
    )

    if not dry_run:
        await db.commit()

    return MemberImportResponse.model_validate(payload)


