@router.post("/{club_id}/promote-waitlist")
async def promote_book_club_waitlist(
    club_id: int,
    staff_user: User = Depends(require_staff),
    db: AsyncSession = Depends(get_db),
    _flag: None = Depends(require_book_club_waitlist_enabled),
):
    """Manual backup: promote as many waitlisted patrons as there are
    free seats. Idempotent — promotes nobody when the club is full."""
    club = await db.scalar(select(BookClub).where(BookClub.id == club_id))
    if club is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Book club not found",
        )

    promoted = 0
    if club.max_members is None:
        promoted = await book_club_service.auto_promote_on_capacity_increase(
            club_id, old_max=0, new_max=None, db=db
        )
    else:
        current = await book_club_service.get_member_count(club_id, db)
        seats = max(0, club.max_members - current)
        for _ in range(seats):
            result = await book_club_service.promote_next_from_waitlist(
                club_id, db
            )
            if result is None:
                break
            promoted += 1
    await db.commit()
    return {"promoted": promoted}


@router.patch("/{club_id}", response_model=BookClubResponse)
async def update_book_club(
    club_id: int,
    request: BookClubUpdate,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> BookClubResponse:
    """Update book club."""
    result = await db.execute(
        select(BookClub)
        .where(BookClub.id == club_id)
        .options(selectinload(BookClub.members), selectinload(BookClub.meetings))
    )
    club = result.scalar_one_or_none()

    if not club:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Book club not found",
        )

    # Check admin permission
    is_club_admin = any(
        m.user_id == current_user.id and m.role == BookClubRole.admin
        for m in club.members
    )
    if not is_club_admin and not is_admin(current_user):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Only club admins can update the club",
        )

    # Capture max_members BEFORE mutation so we can detect a capacity
    # increase and auto-promote from the waitlist afterwards.
    old_max = club.max_members

    # Update fields
    if request.name:
        club.name = request.name
    if request.description is not None:
        club.description = request.description
    if request.max_members is not None:
        club.max_members = request.max_members
    if request.is_public is not None:
        club.is_public = request.is_public
    if request.meeting_frequency:
        club.meeting_frequency = request.meeting_frequency

    new_max = club.max_members
    await db.commit()

    # Capacity grew (or went uncapped) -> drain freed seats from the
    # waitlist. Best-effort, in its own commit so a promotion hiccup
    # doesn't roll back the club edit the staffer already saw succeed.
    if request.max_members is not None and (
        new_max is None or old_max is None or new_max > old_max
    ):
        try:
            await book_club_service.auto_promote_on_capacity_increase(
                club_id, old_max, new_max, db
            )
            await db.commit()
        except Exception:  # noqa: BLE001 - promotion is best-effort
            await db.rollback()
            logger.exception(
                "Auto-promote after capacity increase failed club=%s",
                club_id,
            )

    await db.refresh(club)
    return BookClubResponse.model_validate(club)


