@router.post("/", response_model=BookClubResponse, status_code=status.HTTP_201_CREATED)
async def create_book_club(
    request: BookClubCreate,
    staff_user: User = Depends(require_staff),
    db: AsyncSession = Depends(get_db),
) -> BookClubResponse:
    """Create a new book club. Staff-only operation."""
    club = await book_club_service.create_book_club(
        name=request.name,
        description=request.description,
        created_by=staff_user,
        max_members=request.max_members,
        is_public=request.is_public,
        meeting_frequency=request.meeting_frequency,
        db=db,
    )
    await db.commit()
    # Re-fetch with relationships eagerly loaded to avoid MissingGreenlet
    # during Pydantic serialization (members/meetings are required by response).
    result = await db.execute(
        select(BookClub)
        .where(BookClub.id == club.id)
        .options(selectinload(BookClub.members), selectinload(BookClub.meetings))
    )
    club = result.scalar_one()
    return BookClubResponse.model_validate(club)


@router.get("/", response_model=BookClubListResponse)
async def list_book_clubs(
    skip: int = Query(0, ge=0),
    limit: int = Query(20, ge=1, le=100),
    db: AsyncSession = Depends(get_db),
) -> BookClubListResponse:
    """List all public book clubs."""
    # Count total
    count_result = await db.execute(
        select(func.count(BookClub.id)).where(
            BookClub.is_public == True,
            BookClub.status == BookClubStatus.active,
        )
    )
    total = count_result.scalar() or 0

    # Get clubs
    result = await db.execute(
        select(BookClub)
        .where(
            BookClub.is_public == True,
            BookClub.status == BookClubStatus.active,
        )
        .options(selectinload(BookClub.members), selectinload(BookClub.meetings))
        .order_by(BookClub.created_at.desc())
        .offset(skip)
        .limit(limit)
    )
    clubs = result.scalars().all()

    return BookClubListResponse(
        total=total,
        clubs=[BookClubResponse.model_validate(club) for club in clubs],
    )


