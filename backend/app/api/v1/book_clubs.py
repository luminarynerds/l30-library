@router.patch(
    "/{club_id}/meetings/{meeting_id}/archive",
    response_model=BookClubMeetingResponse,
)
async def archive_book_club_meeting(
    club_id: int,
    meeting_id: int,
    staff_user: User = Depends(require_staff),
    db: AsyncSession = Depends(get_db),
    _flag: None = Depends(require_book_club_history_enabled),
) -> BookClubMeetingResponse:
    """Soft-archive a meeting. Staff-only; gated by
    ``book_club_history_enabled``."""
    # Verify the meeting belongs to the named club so we don't allow
    # archiving a meeting from a different club via URL tampering.
    sanity = await db.execute(
        select(BookClubMeeting).where(
            BookClubMeeting.id == meeting_id,
            BookClubMeeting.book_club_id == club_id,
        )
    )
    if sanity.scalars().first() is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Meeting not found in this club",
        )
    meeting = await book_club_service.archive_meeting(meeting_id, db)
    return BookClubMeetingResponse.model_validate(meeting)


@router.patch(
    "/{club_id}/meetings/{meeting_id}/unarchive",
    response_model=BookClubMeetingResponse,
)
async def unarchive_book_club_meeting(
    club_id: int,
    meeting_id: int,
    staff_user: User = Depends(require_staff),
    db: AsyncSession = Depends(get_db),
    _flag: None = Depends(require_book_club_history_enabled),
) -> BookClubMeetingResponse:
    """Restore an archived meeting. Staff-only; gated by
    ``book_club_history_enabled``."""
    sanity = await db.execute(
        select(BookClubMeeting).where(
            BookClubMeeting.id == meeting_id,
            BookClubMeeting.book_club_id == club_id,
        )
    )
    if sanity.scalars().first() is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Meeting not found in this club",
        )
    meeting = await book_club_service.unarchive_meeting(meeting_id, db)
    return BookClubMeetingResponse.model_validate(meeting)


@router.get(
    "/{club_id}/meetings",
    response_model=List[BookClubMeetingResponse],
)
async def list_book_club_meetings(
    club_id: int,
    archived: str = Query(
        "false",
        pattern="^(false|true|all)$",
        description="Filter: 'false' (active, default), 'true' (archived only), 'all'",
    ),
    staff_user: User = Depends(require_staff),
    db: AsyncSession = Depends(get_db),
) -> List[BookClubMeetingResponse]:
    """List meetings for a club with archive filtering. Staff-only.

    Not gated by ``book_club_history_enabled`` for ``archived=false`` so
    staff retain a meetings list when the feature is off; the ``true`` /
    ``all`` paths are still callable but degenerate to "no archived rows
    exist" because nothing can be archived without the flag.
    """
    # Confirm club exists for a clean 404.
    club_row = await db.execute(select(BookClub).where(BookClub.id == club_id))
    if club_row.scalars().first() is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Book club not found",
        )
    meetings = await book_club_service.list_meetings_for_club(
        club_id=club_id, db=db, archived=archived,
    )
    return [BookClubMeetingResponse.model_validate(m) for m in meetings]
