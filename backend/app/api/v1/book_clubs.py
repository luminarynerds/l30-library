@router.get(
    "/{club_id}/waitlist",
    response_model=WaitlistListResponse,
)
async def get_book_club_waitlist(
    club_id: int,
    staff_user: User = Depends(require_staff),
    db: AsyncSession = Depends(get_db),
    _flag: None = Depends(require_book_club_waitlist_enabled),
) -> WaitlistListResponse:
    """Ordered (FIFO) waitlist for a club. Staff-only; gated by
    ``book_club_waitlist_enabled``."""
    from ...models.book_club import BookClubWaitlistEntry

    club = await db.scalar(select(BookClub).where(BookClub.id == club_id))
    if club is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Book club not found",
        )

    # selectinload the user so display_name/email serialize without a
    # MissingGreenlet (the relationship is lazy="raise").
    rows = (
        (
            await db.execute(
                select(BookClubWaitlistEntry)
                .where(BookClubWaitlistEntry.book_club_id == club_id)
                .options(selectinload(BookClubWaitlistEntry.user))
                .order_by(BookClubWaitlistEntry.created_at.asc())
            )
        )
        .scalars()
        .all()
    )

    entries = []
    for position, entry in enumerate(rows, start=1):
        u = entry.user
        if u is not None:
            display_name = (
                f"{u.first_name or ''} {u.last_name or ''}".strip()
                or u.email
                or f"Patron {entry.user_id}"
            )
            email = u.email
        else:
            display_name = f"Patron {entry.user_id}"
            email = None
        entries.append(
            WaitlistEntryResponse(
                id=entry.id,
                user_id=entry.user_id,
                position=position,
                display_name=display_name,
                email=email,
                created_at=entry.created_at,
                notified_at=entry.notified_at,
            )
        )

    return WaitlistListResponse(
        club_id=club_id, total=len(entries), entries=entries
    )


