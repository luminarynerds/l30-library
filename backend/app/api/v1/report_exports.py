"""
Report Export API - Download reports in CSV, Excel, and PDF formats.

Provides endpoints for exporting structured reports generated by the
ReportFactory framework. Supports all five report types (circulation,
financial, patron_activity, collection, compliance) in four output
formats (JSON, CSV, Excel, PDF).

All endpoints require staff-level authentication.
"""

from app.core.logging import get_logger
from datetime import datetime, timezone
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Query, status
from fastapi.responses import Response
from sqlalchemy.ext.asyncio import AsyncSession

from ...core.database import get_db
from ...models.user import User
from ...services.reports.base import OutputFormat, ReportFilters
from ...services.reports.factory import ReportFactory, ReportType
from .auth import get_current_user
from .dependencies import require_staff

logger = get_logger(__name__)

router = APIRouter(prefix="/reports/export", tags=["report-exports"])


# Maps OutputFormat to HTTP content types and file extensions
_FORMAT_METADATA = {
    OutputFormat.CSV: {
        "media_type": "text/csv",
        "extension": "csv",
    },
    OutputFormat.EXCEL: {
        "media_type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "extension": "xlsx",
    },
    OutputFormat.PDF: {
        "media_type": "application/pdf",
        "extension": "pdf",
    },
    OutputFormat.JSON: {
        "media_type": "application/json",
        "extension": "json",
    },
}


def _parse_output_format(format_str: str) -> OutputFormat:
    normalized = format_str.strip().lower()
    try:
        return OutputFormat(normalized)
    except ValueError:
        valid = ", ".join(f.value for f in OutputFormat)
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Invalid format '{format_str}'. Valid formats: {valid}",
        ) from None


def _parse_report_type(type_str: str) -> ReportType:
    normalized = type_str.strip().lower()
    try:
        return ReportType(normalized)
    except ValueError:
        valid = ", ".join(rt.value for rt in ReportType)
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Invalid report type '{type_str}'. Valid types: {valid}",
        ) from None


@router.get("/{report_type}")
async def export_report(
    report_type: str,
    format: str = Query(
        "csv",
        description="Output format: csv, excel, pdf, or json",
    ),
    start_date: Optional[datetime] = Query(
        None, description="Period start (ISO 8601). Defaults to 90 days ago."
    ),
    end_date: Optional[datetime] = Query(
        None, description="Period end (ISO 8601). Defaults to now."
    ),
    branch_id: Optional[int] = Query(None, description="Filter by branch ID"),
    fiscal_year: Optional[int] = Query(
        None,
        description="Fiscal year for compliance reports (overrides date range)",
    ),
    staff_user: User = Depends(require_staff),
    db: AsyncSession = Depends(get_db),
):
    """
    Generate and download a report in the specified format.

    **Report types:** circulation, financial, patron_activity, collection, compliance

    **Formats:** csv, excel, pdf, json

    Returns a file download with appropriate Content-Type and
    Content-Disposition headers.
    """
    rt = _parse_report_type(report_type)
    output = _parse_output_format(format)

    filters = ReportFilters(
        start_date=start_date,
        end_date=end_date,
        branch_id=branch_id,
        fiscal_year=fiscal_year,
    )

    factory = ReportFactory(db, redis=None)

    try:
        report_bytes = await factory.generate(
            report_type=rt,
            filters=filters,
            output=output,
            use_cache=False,
        )
    except Exception:
        logger.exception("Report generation failed for %s/%s", report_type, format)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Report generation failed. Please try again.",
        ) from None

    meta = _FORMAT_METADATA[output]
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    filename = f"{rt.value}_report_{timestamp}.{meta['extension']}"

    return Response(
        content=report_bytes,
        media_type=meta["media_type"],
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
        },
    )


@router.get("")
async def list_available_exports(
    staff_user: User = Depends(require_staff),
):
    """
    List available report types and supported export formats.

    Useful for UI dropdowns and documentation.
    """
    return {
        "report_types": [
            {
                "id": rt.value,
                "name": rt.value.replace("_", " ").title(),
                "description": _REPORT_DESCRIPTIONS.get(rt, ""),
            }
            for rt in ReportType
        ],
        "formats": [
            {
                "id": fmt.value,
                "name": fmt.value.upper(),
                "media_type": _FORMAT_METADATA[fmt]["media_type"],
                "extension": _FORMAT_METADATA[fmt]["extension"],
            }
            for fmt in OutputFormat
        ],
    }


_REPORT_DESCRIPTIONS = {
    ReportType.CIRCULATION: (
        "Checkout, return, overdue, and hold statistics with daily trends."
    ),
    ReportType.FINANCIAL: (
        "Revenue, fines, waivers, and payment method breakdowns."
    ),
    ReportType.PATRON_ACTIVITY: (
        "New registrations, active patrons, top borrowers, and demographics."
    ),
    ReportType.COLLECTION: (
        "Collection size, format distribution, additions, losses, and turnover."
    ),
    ReportType.COMPLIANCE: (
        "Annual compliance data with year-over-year comparisons (requires fiscal_year)."
    ),
}
