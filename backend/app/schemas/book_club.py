# ======================== MEMBER BULK IMPORT SCHEMAS ========================


class MemberImportRowStatus:

    SUCCESS = "success"
    DUPLICATE = "duplicate"
    NOT_FOUND = "not_found"
    INVALID_EMAIL = "invalid_email"
    INVALID_ROLE = "invalid_role"
    DEACTIVATED = "deactivated"
    PARSE_ERROR = "parse_error"


class MemberImportRowResult(BaseModel):

    row: int = Field(..., description="1-based row number in source CSV (excluding header)")
    email: Optional[str] = Field(None, description="Email from the CSV row, if any")
    patron_id: Optional[int] = Field(None, description="Patron ID from the CSV row, if any")
    role: Optional[str] = Field(None, description="Resolved role (after default_role fallback)")
    status: str = Field(..., description="Outcome status (see MemberImportRowStatus)")
    user_id: Optional[int] = Field(None, description="DB user.id if row resolved to a user")
    message: Optional[str] = Field(None, description="Human-readable detail for errors / skips")


class MemberImportResponse(BaseModel):

    import_id: Optional[str] = Field(
        None,
        description="UUID of the audit row; None for dry_run.",
    )
    dry_run: bool
    total_rows: int
    success_count: int
    skipped_count: int
    error_count: int
    rows: List[MemberImportRowResult]
