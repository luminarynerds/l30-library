from datetime import datetime
from typing import List, Optional

from pydantic import BaseModel, Field

from app.schemas._base import StrictInputSchema


# ======================== BOOK CLUB SCHEMAS ========================


class BookClubMemberBase(BaseModel):
    role: str = Field(..., description="Member role: admin, facilitator, member")


class BookClubMemberResponse(BookClubMemberBase):
    id: int
    user_id: int
    book_club_id: int
    joined_at: datetime

    class Config:
        from_attributes = True


class BookClubCreate(StrictInputSchema):
    name: str = Field(..., min_length=1, max_length=255)
    description: Optional[str] = Field(None, max_length=1000)
    max_members: Optional[int] = Field(None, ge=1)
    is_public: bool = True
    meeting_frequency: Optional[str] = Field(None, max_length=100)


class BookClubUpdate(StrictInputSchema):
    name: Optional[str] = Field(None, min_length=1, max_length=255)
    description: Optional[str] = Field(None, max_length=1000)
    max_members: Optional[int] = Field(None, ge=1)
    is_public: Optional[bool] = None
    meeting_frequency: Optional[str] = Field(None, max_length=100)


class BookClubResponse(BaseModel):
    id: int
    name: str
    description: Optional[str]
    status: str
    max_members: Optional[int]
    is_public: bool
    meeting_frequency: Optional[str]
    created_at: datetime | None = None
    updated_at: datetime | None = None
    created_by_id: Optional[int]
    members: Optional[List[BookClubMemberResponse]] = []
    meetings: Optional[List["BookClubMeetingResponse"]] = []

    class Config:
        from_attributes = True


class WaitlistEntryResponse(BaseModel):
    id: int
    user_id: int
    position: int
    display_name: str
    email: Optional[str] = None
    created_at: datetime | None = None
    notified_at: datetime | None = None

    class Config:
        from_attributes = True


class WaitlistListResponse(BaseModel):
    club_id: int
    total: int
    entries: List[WaitlistEntryResponse] = []


class BookClubListResponse(BaseModel):
    total: int
    clubs: List[BookClubResponse]


