async def checkout_book_club_kit(
    kit_id: int,
    club_id: int,
    user_id: int,
    loan_period_days: int = LOAN_PERIOD_DAYS,
    db: Optional[AsyncSession] = None,
) -> KitCheckout:
    # Check if kit is already checked out
    result = await db.execute(
        select(KitCheckout).where(
            KitCheckout.kit_id == kit_id,
            KitCheckout.status == "active",
        )
    )
    existing_checkout = result.scalar_one_or_none()

    if existing_checkout:
        raise BusinessLogicError(
            code=ErrorCode.CONFLICT,
            message="This kit is already checked out",
        )

    # Create checkout
    due_date = utc_now() + timedelta(days=loan_period_days)

    checkout = KitCheckout(
        kit_id=kit_id,
        book_club_id=club_id,
        user_id=user_id,
        status="active",
        due_date=due_date,
        all_items_returned=False,
    )

    if db:
        db.add(checkout)
        await db.flush()

    return checkout


