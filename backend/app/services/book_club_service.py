# ======================== KIT AVAILABILITY CALENDAR ========================


async def get_kit_availability_calendar(
    kit_id: int,
    days_ahead: int = 90,
    db: Optional[AsyncSession] = None,
) -> dict:
    now = utc_now()
    future_date = now + timedelta(days=days_ahead)

    # Get all checkouts for this kit
    result = await db.execute(
        select(KitCheckout).where(
            KitCheckout.kit_id == kit_id,
            KitCheckout.checked_out_at <= future_date,
        )
    )
    checkouts = result.scalars().all()

    # Build calendar
    calendar = {}
    for checkout in checkouts:
        current = checkout.checked_out_at
        while current < checkout.due_date:
            date_str = current.date().isoformat()
            if date_str not in calendar:
                calendar[date_str] = {"available": True, "checkouts": []}
            calendar[date_str]["available"] = False
            calendar[date_str]["checkouts"].append(
                {
                    "checkout_id": checkout.id,
                    "club_id": checkout.book_club_id,
                }
            )
            current += timedelta(days=1)

    return {
        "kit_id": kit_id,
        "calendar": calendar,
        "period": {
            "start": now.date().isoformat(),
            "end": future_date.date().isoformat(),
        },
    }


