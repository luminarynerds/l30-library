async def calculate_kit_availability(
    kit_id: int,
    db: AsyncSession,
) -> dict:
    # Get kit
    result = await db.execute(
        select(BookClubKit).where(BookClubKit.id == kit_id)
    )
    kit = result.scalar_one_or_none()

    if not kit:
        raise ResourceNotFoundError(message="Kit not found")

    # Count active checkouts
    checkout_result = await db.execute(
        select(func.count(KitCheckout.id)).where(
            KitCheckout.kit_id == kit_id,
            KitCheckout.status == "active",
        )
    )
    active_checkouts = checkout_result.scalar() or 0

    # Get pending holds
    hold_result = await db.execute(
        select(func.count(GroupHold.id)).where(
            GroupHold.kit_id == kit_id,
            GroupHold.status == "pending",
        )
    )
    pending_holds = hold_result.scalar() or 0

    return {
        "kit_id": kit_id,
        "total_copies": kit.total_copies,
        "active_checkouts": active_checkouts,
        "available_copies": max(0, kit.total_copies - active_checkouts),
        "pending_holds": pending_holds,
        "is_available": (kit.total_copies - active_checkouts) > 0,
    }


# ======================== GROUP HOLDS ========================


async def place_group_hold(
    kit_id: int,
    club_id: int,
    requested_by_id: int,
    db: AsyncSession,
) -> GroupHold:
    # Get current queue position
    position_result = await db.execute(
        select(func.max(GroupHold.position_in_queue)).where(
            GroupHold.kit_id == kit_id,
            GroupHold.status.in_(["pending", "ready"]),
        )
    )
    max_position = position_result.scalar() or 0
    position = max_position + 1

    # Expiration: 7 days from now
    expires_at = utc_now() + timedelta(days=7)

    hold = GroupHold(
        kit_id=kit_id,
        book_club_id=club_id,
        requested_by_id=requested_by_id,
        status="pending",
        position_in_queue=position,
        expires_at=expires_at,
    )

    db.add(hold)
    await db.flush()

    return hold


async def get_group_hold_queue(
    kit_id: int,
    db: AsyncSession,
) -> List[GroupHold]:
    result = await db.execute(
        select(GroupHold)
        .where(
            GroupHold.kit_id == kit_id,
            GroupHold.status.in_(["pending", "ready"]),
        )
        .order_by(GroupHold.position_in_queue)
    )
    return result.scalars().all()


async def cancel_group_hold(
    hold_id: int,
    db: AsyncSession,
) -> bool:
    result = await db.execute(
        select(GroupHold).where(GroupHold.id == hold_id)
    )
    hold = result.scalar_one_or_none()

    if not hold:
        return False

    hold.status = "cancelled"
    await db.flush()
    return True


