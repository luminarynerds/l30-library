async def search_discussions(
    club_id: int,
    q: str,
    db: AsyncSession,
    *,
    include_archived: bool = False,
    date_from: Optional[datetime] = None,
    date_to: Optional[datetime] = None,
    limit: int = 50,
) -> List[dict]:
    from sqlalchemy import text

    if not q or not q.strip():
        return []

    params: dict = {
        "club_id": club_id,
        "q": q,
        "limit": limit,
    }

    archived_clause = ""
    if not include_archived:
        archived_clause = "AND m.is_archived = false"

    date_from_clause = ""
    if date_from is not None:
        date_from_clause = "AND m.meeting_date >= :date_from"
        params["date_from"] = date_from

    date_to_clause = ""
    if date_to is not None:
        date_to_clause = "AND m.meeting_date <= :date_to"
        params["date_to"] = date_to

    sql = text(f"""
        SELECT
            d.id AS id,
            d.meeting_id AS meeting_id,
            m.title AS meeting_title,
            m.meeting_date AS meeting_scheduled_at,
            m.is_archived AS meeting_is_archived,
            d.author_display_name AS author_display_name,
            d.created_at AS created_at,
            ts_headline(
                'english',
                -- HTML-escape the patron-authored body BEFORE highlighting so the
                -- snippet is escaped text + ts_headline's own <b> tags. The client
                -- renders this via dangerouslySetInnerHTML, so this is the
                -- stored-XSS guard (ts_headline itself does not escape the body).
                replace(replace(replace(d.body, '&', '&amp;'), '<', '&lt;'), '>', '&gt;'),
                plainto_tsquery('english', :q),
                'MaxFragments=2,MaxWords=15,MinWords=3'
            ) AS snippet,
            ts_rank(d.search_vector, plainto_tsquery('english', :q)) AS rank
        FROM book_club_discussions d
        JOIN book_club_meetings m ON m.id = d.meeting_id
        WHERE m.book_club_id = :club_id
          AND d.search_vector @@ plainto_tsquery('english', :q)
          {archived_clause}
          {date_from_clause}
          {date_to_clause}
        ORDER BY rank DESC, d.created_at DESC
        LIMIT :limit
    """)

    result = await db.execute(sql, params)
    hits: List[dict] = []
    for row in result.mappings():
        hits.append({
            "id": row["id"],
            "meeting_id": row["meeting_id"],
            "meeting_title": row["meeting_title"],
            "meeting_scheduled_at": row["meeting_scheduled_at"],
            "meeting_is_archived": row["meeting_is_archived"],
            "author_display_name": row["author_display_name"] or "",
            "snippet": row["snippet"] or "",
            "created_at": row["created_at"],
            "rank": float(row["rank"]) if row["rank"] is not None else 0.0,
        })
    return hits


async def list_meetings_for_club(
    club_id: int,
    db: AsyncSession,
    *,
    archived: str = "false",
) -> List[BookClubMeeting]:
    query = select(BookClubMeeting).where(BookClubMeeting.book_club_id == club_id)
    if archived == "true":
        query = query.where(BookClubMeeting.is_archived.is_(True))
    elif archived == "false":
        query = query.where(BookClubMeeting.is_archived.is_(False))
    # "all" => no extra filter
    query = query.order_by(BookClubMeeting.meeting_date.desc())
    result = await db.execute(query)
    return list(result.scalars().all())
# ======================== BULK MEMBER CSV IMPORT ========================

import re as _re

# Pragmatic email regex aligned with what L30 User.email accepts. We match
# what existing patron-create flows accept (no full RFC 5322 — that has known
# false-positives on edge cases nobody is putting in a CSV).
_EMAIL_RE = _re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")

# Public so the endpoint can detect "too many rows" before invoking the
# service. Spec mandates 500.
MAX_IMPORT_ROWS = 500


class ImportRowCapExceeded(Exception):
    pass


async def import_members(
    *,
    club_id: int,
    rows: List[dict],
    default_role: str,
    dry_run: bool,
    imported_by_id: Optional[int],
    db: AsyncSession,
) -> dict:
    if len(rows) > MAX_IMPORT_ROWS:
        raise ImportRowCapExceeded(
            f"CSV exceeds {MAX_IMPORT_ROWS} row limit (got {len(rows)})"
        )

    valid_roles = {"admin", "facilitator", "member"}
    if default_role not in valid_roles:
        # Shouldn't happen — endpoint validates — but guard anyway.
        default_role = "member"

    # ---- batch lookups -------------------------------------------------

    # 1. Collect candidates from rows (skip rows that have neither key).
    emails = []
    patron_ids = []
    for r in rows:
        e = (r.get("email") or "").strip().lower() or None
        try:
            pid = int(r["patron_id"]) if r.get("patron_id") not in (None, "", " ") else None
        except (ValueError, TypeError):
            pid = None
        if e:
            emails.append(e)
        if pid is not None:
            patron_ids.append(pid)

    # 2. Existing members in this club (one query).
    existing_member_ids: set[int] = set()
    if True:
        res = await db.execute(
            select(BookClubMember.user_id).where(
                BookClubMember.book_club_id == club_id
            )
        )
        existing_member_ids = {uid for (uid,) in res.all()}

    # 3. Users by email (one query, lowercase).
    users_by_email: dict[str, User] = {}
    if emails:
        # Email is encrypted: look up via the email_hash blind index.
        hashes = {email_blind_hash(e) for e in emails}
        res = await db.execute(
            select(User).where(User.email_hash.in_(hashes))
        )
        users_by_email = {u.email.lower(): u for u in res.scalars().all()}

    # 4. Users by patron_id (one query).
    users_by_id: dict[int, User] = {}
    if patron_ids:
        res = await db.execute(
            select(User).where(User.id.in_(set(patron_ids)))
        )
        users_by_id = {u.id: u for u in res.scalars().all()}

    # ---- per-row processing -------------------------------------------

    out_rows: list[dict] = []
    success = 0
    skipped = 0
    errors = 0
    # In-file dedup tracker (user_id of users we'd add this run).
    pending_user_ids: set[int] = set()

    new_members: list[BookClubMember] = []

    for idx, r in enumerate(rows, start=1):
        row_out = {
            "row": idx,
            "email": (r.get("email") or "").strip() or None,
            "patron_id": None,
            "role": None,
            "status": "",
            "user_id": None,
            "message": None,
        }
        raw_email = (r.get("email") or "").strip().lower() or None
        raw_pid_str = r.get("patron_id")
        try:
            raw_pid = (
                int(raw_pid_str) if raw_pid_str not in (None, "", " ") else None
            )
            row_out["patron_id"] = raw_pid
        except (ValueError, TypeError):
            row_out["status"] = "parse_error"
            row_out["message"] = "patron_id must be an integer"
            out_rows.append(row_out)
            errors += 1
            continue

        # Role resolution.
        raw_role = (r.get("role") or "").strip().lower() or default_role
        if raw_role not in valid_roles:
            row_out["role"] = raw_role
            row_out["status"] = "invalid_role"
            row_out["message"] = f"Role must be one of: {', '.join(sorted(valid_roles))}"
            out_rows.append(row_out)
            errors += 1
            continue
        row_out["role"] = raw_role

        # Need at least one identifier.
        if raw_email is None and raw_pid is None:
            row_out["status"] = "parse_error"
            row_out["message"] = "Row must include email or patron_id"
            out_rows.append(row_out)
            errors += 1
            continue

        # Email format check (only when email is the identifier, or when
        # both provided — patron_id wins on resolve but we still surface a
        # bad email format).
        if raw_email is not None and not _EMAIL_RE.match(raw_email):
            row_out["status"] = "invalid_email"
            row_out["message"] = "Email does not look valid"
            out_rows.append(row_out)
            errors += 1
            continue

        # Resolve user: patron_id wins.
        user = None
        if raw_pid is not None and raw_pid in users_by_id:
            user = users_by_id[raw_pid]
        elif raw_email is not None and raw_email in users_by_email:
            user = users_by_email[raw_email]

        if user is None:
            row_out["status"] = "not_found"
            row_out["message"] = "No matching account; ask the patron to sign up first."
            out_rows.append(row_out)
            skipped += 1
            continue

        row_out["user_id"] = user.id

        if not user.is_active:
            row_out["status"] = "deactivated"
            row_out["message"] = "Account is inactive."
            out_rows.append(row_out)
            skipped += 1
            continue

        if user.id in existing_member_ids:
            row_out["status"] = "duplicate"
            row_out["message"] = "Already a member of this club."
            out_rows.append(row_out)
            skipped += 1
            continue

        if user.id in pending_user_ids:
            # In-file dedup: first occurrence already counted.
            row_out["status"] = "duplicate"
            row_out["message"] = "Already listed earlier in this CSV."
            out_rows.append(row_out)
            skipped += 1
            continue

        # Success path.
        pending_user_ids.add(user.id)
        row_out["status"] = "success"
        out_rows.append(row_out)
        success += 1

        if not dry_run:
            new_members.append(
                BookClubMember(
                    book_club_id=club_id,
                    user_id=user.id,
                    role=BookClubRole(raw_role),
                )
            )

    # ---- writes --------------------------------------------------------

    import_id: Optional[str] = None

    if not dry_run:
        # Insert new memberships (within the existing endpoint transaction —
        # the endpoint awaits db.commit() after).
        for m in new_members:
            db.add(m)

        # Lazy import to avoid widening the module-level import block above.
        from ..models.book_club import BookClubMemberImport

        audit = BookClubMemberImport(
            book_club_id=club_id,
            imported_by_id=imported_by_id,
            row_count=len(rows),
            success_count=success,
            skipped_count=skipped,
            error_count=errors,
            raw_outcome={
                "rows": out_rows,
                "default_role": default_role,
            },
        )
        db.add(audit)
        await db.flush()  # populate audit.id (UUID server_default)
        import_id = str(audit.id)

    return {
        "import_id": import_id,
        "dry_run": dry_run,
        "total_rows": len(rows),
        "success_count": success,
        "skipped_count": skipped,
        "error_count": errors,
        "rows": out_rows,
    }


# ======================== WAITLIST + CAPACITY SIGNALS ========================
# Added for the book-club waitlist feature (spec
# 2026-05-18-l30-book-club-waitlist). Patron join/leave waitlist routing
# lives in BookClubPatronService (next to join_club/leave_club); this
# section holds the shared count/position helpers, the atomic FIFO
# promotion (FOR UPDATE SKIP LOCKED), the capacity-increase auto-promote
# loop, and the archive-with-waitlist teardown. Position is never stored
# — it is derived from created_at ordering at query time.


async def get_member_count(club_id: int, db: AsyncSession) -> int:
    return (
        await db.scalar(
            select(func.count())
            .select_from(BookClubMember)
            .where(BookClubMember.book_club_id == club_id)
        )
    ) or 0


async def get_waitlist_count(club_id: int, db: AsyncSession) -> int:
    return (
        await db.scalar(
            select(func.count())
            .select_from(BookClubWaitlistEntry)
            .where(BookClubWaitlistEntry.book_club_id == club_id)
        )
    ) or 0


async def get_patron_waitlist_position(
    club_id: int, user_id: int, db: AsyncSession
) -> Optional[int]:
    mine = await db.scalar(
        select(BookClubWaitlistEntry.created_at).where(
            BookClubWaitlistEntry.book_club_id == club_id,
            BookClubWaitlistEntry.user_id == user_id,
        )
    )
    if mine is None:
        return None
    ahead = (
        await db.scalar(
            select(func.count())
            .select_from(BookClubWaitlistEntry)
            .where(
                BookClubWaitlistEntry.book_club_id == club_id,
                BookClubWaitlistEntry.created_at <= mine,
            )
        )
    ) or 0
    return int(ahead)


async def is_club_full(club: BookClub, db: AsyncSession) -> bool:
    if club.max_members is None:
        return False
    count = await get_member_count(club.id, db)
    return count >= club.max_members


async def _send_waitlist_promotion_notification(
    user_id: int, club: BookClub, db: AsyncSession
) -> None:
    user = await db.scalar(select(User).where(User.id == user_id))
    if user is None or not user.email:
        return
    # ALWAYS log before send: L30's daily-cap safeguard silently drops
    # the message and still returns HTTP 200 (feedback memo:
    # l30_email_safeguard_cap_masks_failure).
    logger.info(
        "EMAIL_SEND book_club_waitlist_promoted user=%s club=%s",
        user_id,
        club.id,
    )
    try:
        from app.core.email import send_waitlist_promotion_email

        await send_waitlist_promotion_email(user, club)
    except Exception:  # noqa: BLE001 - courtesy email, never fatal
        logger.exception(
            "Waitlist promotion email failed user=%s club=%s",
            user_id,
            club.id,
        )


async def promote_next_from_waitlist(
    club_id: int, db: AsyncSession
) -> Optional[int]:
    club = await db.get(BookClub, club_id)
    if club is None:
        return None
    if club.max_members is not None:
        current = await get_member_count(club_id, db)
        if current >= club.max_members:
            return None

    entry = await db.scalar(
        select(BookClubWaitlistEntry)
        .where(BookClubWaitlistEntry.book_club_id == club_id)
        .order_by(BookClubWaitlistEntry.created_at.asc())
        .limit(1)
        .with_for_update(skip_locked=True)
    )
    if entry is None:
        return None

    # Guard against a stale entry whose user is already a member (e.g.
    # added directly by staff while waitlisted) — uphold uq_member.
    already = await db.scalar(
        select(func.count())
        .select_from(BookClubMember)
        .where(
            BookClubMember.book_club_id == club_id,
            BookClubMember.user_id == entry.user_id,
        )
    )
    promoted_user_id = entry.user_id
    if not already:
        db.add(
            BookClubMember(
                book_club_id=club_id,
                user_id=entry.user_id,
                role=BookClubRole.member,
            )
        )
    await db.delete(entry)
    await db.flush()
    if not already:
        await _send_waitlist_promotion_notification(
            promoted_user_id, club, db
        )
        return promoted_user_id
    return None


async def auto_promote_on_capacity_increase(
    club_id: int, old_max: Optional[int], new_max: Optional[int], db: AsyncSession
) -> int:
    # No change, or capacity decreased: nothing to do.
    if new_max is not None and old_max is not None and new_max <= old_max:
        return 0

    current = await get_member_count(club_id, db)
    if new_max is None:
        # Uncapped now — drain the whole waitlist.
        seats = await get_waitlist_count(club_id, db)
    else:
        seats = max(0, new_max - current)

    promoted = 0
    for _ in range(seats):
        result = await promote_next_from_waitlist(club_id, db)
        if result is None:
            break
        promoted += 1
    return promoted


async def archive_book_club_with_waitlist(
    club_id: int, db: AsyncSession
) -> int:
    club = await db.get(BookClub, club_id)
    if club is None:
        raise ResourceNotFoundError("Book club not found")

    entries = (
        (
            await db.execute(
                select(BookClubWaitlistEntry)
                .where(BookClubWaitlistEntry.book_club_id == club_id)
                .order_by(BookClubWaitlistEntry.created_at.asc())
            )
        )
        .scalars()
        .all()
    )

    notified = 0
    for entry in entries:
        user = await db.scalar(
            select(User).where(User.id == entry.user_id)
        )
        if user is not None and user.email:
            logger.info(
                "EMAIL_SEND book_club_waitlist_archived_notice "
                "user=%s club=%s",
                entry.user_id,
                club_id,
            )
            try:
                from app.core.email import (
                    send_waitlist_archived_notice_email,
                )

                # One discrete send per patron: Resend 422s on duplicate
                # tag names within a single batch request.
                await send_waitlist_archived_notice_email(user, club)
                notified += 1
            except Exception:  # noqa: BLE001 - courtesy email
                logger.exception(
                    "Waitlist archive notice failed user=%s club=%s",
                    entry.user_id,
                    club_id,
                )
        await db.delete(entry)

    club.status = BookClubStatus.archived
    await db.flush()
    return notified
