async def create_book_club(
    name: str,
    description: Optional[str],
    created_by: User,
    max_members: Optional[int] = None,
    is_public: bool = True,
    meeting_frequency: Optional[str] = None,
    db: Optional[AsyncSession] = None,
) -> BookClub:
    club = BookClub(
        name=name,
        description=description,
        created_by_id=created_by.id,
        max_members=max_members,
        is_public=is_public,
        meeting_frequency=meeting_frequency,
        status=BookClubStatus.active,
    )

    # Add creator as admin member
    admin_member = BookClubMember(
        book_club=club,
        user_id=created_by.id,
        role=BookClubRole.admin,
    )
    club.members.append(admin_member)

    if db:
        db.add(club)
        await db.flush()

    return club


async def add_book_club_member(
    club: BookClub,
    user: User,
    role: BookClubRole = BookClubRole.member,
    db: Optional[AsyncSession] = None,
) -> BookClubMember:
    # Check if already a member
    if any(m.user_id == user.id for m in club.members):
        raise BusinessLogicError(
            code=ErrorCode.CONFLICT,
            message=f"User is already a member of {club.name}",
        )

    # Check member limit
    if club.max_members and len(club.members) >= club.max_members:
        raise BusinessLogicError(
            code=ErrorCode.QUOTA_EXCEEDED,
            message=f"Book club {club.name} has reached its maximum of {club.max_members} members",
        )

    member = BookClubMember(
        book_club_id=club.id,
        user_id=user.id,
        role=role,
    )

    if db:
        db.add(member)
        await db.flush()

    return member


async def remove_book_club_member(
    club_id: int,
    user_id: int,
    db: AsyncSession,
) -> bool:
    result = await db.execute(
        select(BookClubMember).where(
            BookClubMember.book_club_id == club_id,
            BookClubMember.user_id == user_id,
        )
    )
    member = result.scalar_one_or_none()

    if not member:
        return False

    await db.delete(member)
    return True


