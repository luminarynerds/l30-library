from app.core.logging import get_logger
from datetime import datetime, timezone
from typing import List, Optional

from sqlalchemy.ext.asyncio import AsyncSession
from ..core.branding import branding

from ..models.board.report import BoardReport
from ..core.config import get_settings
from ..core.email import send_email

logger = get_logger(__name__)
settings = get_settings()


class BoardReportEmailService:

    @staticmethod
    async def send_report_to_recipients(
        db: AsyncSession,
        report: BoardReport,
        recipient_emails: List[str],
        include_attachments: bool = True,
    ) -> tuple[bool, Optional[str]]:
        if not recipient_emails:
            return False, "No recipient emails provided"

        try:
            # Prepare email attachments
            attachments = []
            if include_attachments:
                if report.file_powerpoint:
                    attachments.append({
                        "filename": f"board_report_{report.id}.pptx",
                        "content": report.file_powerpoint,
                        "mimetype": "application/vnd.openxmlformats-officedocument.presentationml.presentation",
                    })
                if report.file_pdf:
                    attachments.append({
                        "filename": f"board_report_{report.id}.pdf",
                        "content": report.file_pdf,
                        "mimetype": "application/pdf",
                    })

            # Prepare email content
            period_str = f"{report.report_period_start.strftime('%B %d, %Y')} - {report.report_period_end.strftime('%B %d, %Y')}"

            email_body = f"""
<html>
<body style="font-family: Arial, sans-serif; line-height: 1.6; color: #333;">
    <div style="max-width: 600px; margin: 0 auto;">
        <h1 style="color: #1F4E79; margin-bottom: 20px;">Board Report</h1>

        <p>Dear Board Member,</p>

        <p>Please find attached the comprehensive board report for the period of <strong>{period_str}</strong>.</p>

        <div style="background-color: #f5f5f5; padding: 15px; border-left: 4px solid #1F4E79; margin: 20px 0;">
            <h3 style="color: #1F4E79; margin-top: 0;">Report Highlights:</h3>
            <ul>
                <li><strong>Circulation Metrics:</strong> Comprehensive checkout and hold statistics</li>
                <li><strong>Financial Performance:</strong> Revenue analysis and outstanding balance tracking</li>
                <li><strong>Patron Engagement:</strong> New patron acquisition and active user metrics</li>
                <li><strong>Collection Status:</strong> Inventory levels and availability rates</li>
                <li><strong>Website Traffic:</strong> Pageviews, visitors, and top pages from public site analytics</li>
            </ul>
        </div>

        <p>The report includes:</p>
        <ul>
            <li>Executive summary with key metrics</li>
            <li>Detailed circulation and financial analysis</li>
            <li>Patron engagement insights</li>
            <li>Collection availability analysis</li>
            <li>Period-over-period trend comparisons</li>
            <li>Discussion prompts for board consideration</li>
        </ul>

        <p><strong>Available Formats:</strong></p>
        <ul>
            <li>PowerPoint presentation (for board meetings)</li>
            <li>PDF document (for archival and printing)</li>
        </ul>

        <p>If you have any questions about this report or need additional analysis, please don't hesitate to reach out.</p>

        <hr style="border: none; border-top: 1px solid #ddd; margin: 30px 0;">

        <p style="font-size: 12px; color: #666;">
            This is an automated report generated by the {branding.library_name} Board Report System.<br>
            Report ID: {report.id}<br>
            Generated: {datetime.now(timezone.utc).strftime('%B %d, %Y at %I:%M %p %Z')}
        </p>
    </div>
</body>
</html>
"""

            # Send emails to all recipients
            # core.email.send_email supports a single attachment; prefer PDF, fall back to PPTX
            attachment_data: Optional[bytes] = None
            attachment_filename: Optional[str] = None
            if attachments:
                for att in attachments:
                    if att["mimetype"] == "application/pdf":
                        attachment_data = att["content"]
                        attachment_filename = att["filename"]
                        break
                if attachment_data is None:
                    attachment_data = attachments[0]["content"]
                    attachment_filename = attachments[0]["filename"]

            failed_recipients = []
            for email in recipient_emails:
                try:
                    await send_email(
                        to_email=email,
                        subject=f"Board Report - {period_str}",
                        html_content=email_body,
                        attachment_data=attachment_data,
                        attachment_filename=attachment_filename,
                    )
                    logger.info(f"Board report {report.id} sent to {email}")
                except Exception as e:  # noqa: BLE001 -- per-recipient boundary: one send failure must not block other recipients
                    logger.error(f"Failed to send board report to {email}: {e}")
                    failed_recipients.append(email)

            # Update report email status
            report.email_sent = len(failed_recipients) < len(recipient_emails)
            report.email_sent_at = datetime.now(timezone.utc)

            if failed_recipients:
                report.email_status = "partial"
                report.email_error_message = f"Failed to send to: {', '.join(failed_recipients)}"
                await db.commit()
                return False, report.email_error_message
            else:
                report.email_status = "sent"
                report.email_error_message = None
                await db.commit()
                return True, None

        except Exception as e:
            logger.error(f"Error sending board reports: {e}", exc_info=True)
            report.email_status = "failed"
            report.email_error_message = str(e)
            await db.commit()
            return False, str(e)

    @staticmethod
    async def send_scheduled_report(
        db: AsyncSession,
        report_id: int,
        recipient_emails: List[str],
    ) -> tuple[bool, Optional[str]]:
        from sqlalchemy import select

        query = select(BoardReport).where(BoardReport.id == report_id)
        result = await db.execute(query)
        report = result.scalars().first()

        if not report:
            return False, f"Report {report_id} not found"

        return await BoardReportEmailService.send_report_to_recipients(
            db=db,
            report=report,
            recipient_emails=recipient_emails,
            include_attachments=True,
        )
