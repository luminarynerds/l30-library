export function ProgressBar({ value, max, color = 'bg-lsc-rose' }: { value: number; max: number; color?: string }) {
  const pct = max > 0 ? Math.min(100, Math.round((value / max) * 100)) : 0
  return (
    <div className="flex items-center gap-2">
      <div className="flex-1 bg-lsc-border dark:bg-earth-700 rounded-full h-2">
        <div className={`${color} h-2 rounded-full transition-all`} style={{ width: `${pct}%` }} />
      </div>
      <span className="text-xs text-lsc-dark/70 dark:text-lsc-cream/70 w-8 text-right">{pct}%</span>
    </div>
  )
}
